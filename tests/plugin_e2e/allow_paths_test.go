package plugin_e2e

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/tidwall/gjson"
)

// allowPathsRoot is the directory the e2e plugin declares: a literal under
// /var/tmp, which no built-in root contains, which every account can write
// (including the root user CI runs as, whose home is a deny root), and which
// is stable so the fork build cache key does not change per run.
const allowPathsRoot = "/var/tmp/lark-cli-e2e-allow-paths"

const allowPathsPlugin = `// Code generated by plugin_e2e; DO NOT EDIT.
package plugin

import "github.com/larksuite/cli/extension/platform"

func init() {
	platform.Register(
		platform.NewPlugin("allow-paths", "0.1.0").
			AllowPaths("` + allowPathsRoot + `").
			MustBuild())
}
`

// TestAllowPathsPin proves the grant at the binary boundary: a real command's
// --output validation refuses the directory in a fork without the declaration
// and accepts it in a fork that declares it, and `config plugins show` lists
// the declaration as written. auth qrcode is the command because it writes a
// file through the strict tier without credentials or network.
func TestAllowPathsPin(t *testing.T) {
	if info, err := os.Stat(filepath.Dir(allowPathsRoot)); err != nil || !info.IsDir() {
		t.Skipf("%s unavailable: %v", filepath.Dir(allowPathsRoot), err)
	}
	// The fixed root is shared with other runs and possibly other users, so
	// work in a private sub-directory and remove exactly what this run made:
	// the sub-directory, and the root only if this run created it (Remove is
	// not recursive, so a root that gained other content is left alone).
	created := false
	if _, err := os.Stat(allowPathsRoot); os.IsNotExist(err) {
		if err := os.Mkdir(allowPathsRoot, 0o777); err != nil {
			t.Fatalf("mkdir %s: %v", allowPathsRoot, err)
		}
		created = true
	}
	dir, err := os.MkdirTemp(allowPathsRoot, "run-")
	if err != nil {
		t.Fatalf("mkdtemp under %s: %v", allowPathsRoot, err)
	}
	t.Cleanup(func() {
		_ = os.RemoveAll(dir)
		if created {
			_ = os.Remove(allowPathsRoot)
		}
	})
	target := filepath.Join(dir, "qr.png")

	baseline := buildFork(t, "smoke", noopPlugin)
	res := run(t, baseline, "auth", "qrcode", "https://example.com/verify", "--output", target)
	if res.exit == 0 {
		t.Fatalf("baseline fork accepted %q; the fixture is not outside the built-in roots\nstdout=%s\nstderr=%s", target, res.stdout, res.stderr)
	}
	if !strings.Contains(res.stdout+res.stderr, "allowlist") {
		t.Fatalf("baseline rejection should cite the allowlist\nstdout=%s\nstderr=%s", res.stdout, res.stderr)
	}

	bin := buildFork(t, "allow-paths", allowPathsPlugin)
	res = run(t, bin, "auth", "qrcode", "https://example.com/verify", "--output", target)
	if res.exit != 0 {
		t.Fatalf("fork with AllowPaths refused %q: exit=%d\nstdout=%s\nstderr=%s", target, res.exit, res.stdout, res.stderr)
	}
	if _, err := os.Stat(target); err != nil {
		t.Fatalf("qr code was not written to the declared root: %v", err)
	}

	res = run(t, bin, "config", "plugins", "show")
	if res.exit != 0 {
		t.Fatalf("config plugins show: exit=%d stderr=%s", res.exit, res.stderr)
	}
	if got := gjson.Get(res.stdout, `plugins.#(name=="allow-paths").allow_paths.0`).String(); got != allowPathsRoot {
		t.Fatalf("allow_paths not surfaced as declared, got %q in:\n%s", got, res.stdout)
	}
}
