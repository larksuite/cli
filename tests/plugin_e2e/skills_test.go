// skillSelectionPlugin proves that a plugin's Allow/Remove selection composes
// against the base embedded by the external wrapper main. Before the wrapper
// wired cmd.SetEmbeddedSkillContent, this configuration installed a fatal guard
// that made every command exit 2.
const skillSelectionPlugin = `// Code generated by plugin_e2e; DO NOT EDIT.
package plugin

import "github.com/larksuite/cli/extension/platform"

func init() {
	platform.Register(
		platform.NewPlugin("skill-selection", "0.1.0").
			EmbeddedSkills(&platform.SkillsOverlay{
				Allow:  []string{"lark-a", "lark-b"},
				Remove: []string{"lark-b"},
			}).
			MustBuild())
}
`

