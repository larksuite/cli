func TestForkMainWiresEmbeddedSkillsWithoutOverlay(t *testing.T) {
	bin := buildFork(t, "smoke", noopPlugin)
	t.Setenv("PATH", filepath.Dir(bin)+string(os.PathListSeparator)+os.Getenv("PATH"))
	const cli = "lark-cli"

	res := run(t, cli, "skills", "list")
	if res.exit != 0 || !gjson.Valid(res.stdout) {
		t.Fatalf("skills list exit=%d stdout=%s stderr=%s", res.exit, res.stdout, res.stderr)
	}
	if got := gjson.Get(res.stdout, "count").Int(); got != 4 {
		t.Fatalf("skills count=%d want 4; stdout=%s", got, res.stdout)
	}
	if got := gjson.Get(res.stdout, "skills.#.name").Array(); len(got) != 4 ||
		got[0].String() != "lark-a" || got[1].String() != "lark-b" ||
		got[2].String() != "lark-doc" || got[3].String() != "lark-shared" {
		t.Fatalf("skill names=%v want [lark-a lark-b lark-doc lark-shared]; stdout=%s", got, res.stdout)
	}

	docsHelp := run(t, cli, "docs", "--help")
	if docsHelp.exit != 0 ||
		!strings.Contains(docsHelp.stdout,
			"Domain guide (concepts, command choice, conventions): lark-cli skills read lark-doc") ||
		strings.Contains(docsHelp.stdout, "Domain skills (concepts, command choice, conventions):") {
		t.Fatalf("docs help canonical skill pointer missing: exit=%d stdout=%s stderr=%s",
			docsHelp.exit, docsHelp.stdout, docsHelp.stderr)
	}
	mainSkill := run(t, cli, "skills", "read", "lark-doc")
	if mainSkill.exit != 0 || !strings.Contains(mainSkill.stdout, "name: lark-doc") {
		t.Fatalf("canonical docs skill pointer is not readable: exit=%d stdout=%s stderr=%s",
			mainSkill.exit, mainSkill.stdout, mainSkill.stderr)
	}

	for _, tc := range []struct {
		shortcut   string
		references []string
	}{
		{shortcut: "+create", references: []string{"lark-doc-create.md", "lark-doc-xml.md", "lark-doc-md.md"}},
		{shortcut: "+fetch", references: []string{"lark-doc-fetch.md"}},
		{shortcut: "+update", references: []string{"lark-doc-update.md", "lark-doc-xml.md", "lark-doc-md.md"}},
		{shortcut: "+history-list", references: []string{"lark-doc-history.md"}},
		{shortcut: "+history-revert", references: []string{"lark-doc-history.md"}},
		{shortcut: "+history-revert-status", references: []string{"lark-doc-history.md"}},
	} {
		help := run(t, cli, "docs", tc.shortcut, "--help")
		if help.exit != 0 {
			t.Errorf("docs %s help failed: exit=%d stdout=%s stderr=%s",
				tc.shortcut, help.exit, help.stdout, help.stderr)
			continue
		}
		for _, reference := range tc.references {
			path := "references/" + reference
			pointer := "lark-cli skills read lark-doc/" + path
			if !strings.Contains(help.stdout, pointer) {
				t.Errorf("docs %s reference pointer %q missing; stdout=%s",
					tc.shortcut, pointer, help.stdout)
				continue
			}
			// Execute the exact binary name and arguments printed by help:
			// PATH resolution here catches a fork shipped only as "larkx".
			rules := run(t, cli, "skills", "read", "lark-doc/"+path)
			if rules.exit != 0 || !strings.Contains(rules.stdout, "Plugin E2E "+reference) {
				t.Errorf("docs %s reference pointer %q is not readable: exit=%d stdout=%s stderr=%s",
					tc.shortcut, pointer, rules.exit, rules.stdout, rules.stderr)
			}
		}
	}
}

func TestForkDomainHelpDisplaysConfiguredSkills(t *testing.T) {
	affordanceSrc := strings.Replace(
		customerAffordanceDocs,
		"> skill: lark-doc\n",
		"> skill: lark-doc\n\n## Skills\n- lark-a\n- lark-missing\n",
		1,
	)
	bin := buildForkWithAffordance(t, "domain-skills", noopPlugin, affordanceSrc)

	help := run(t, bin, "docs", "--help")
	if help.exit != 0 {
		t.Fatalf("docs help: exit=%d stdout=%s stderr=%s", help.exit, help.stdout, help.stderr)
	}
	if !strings.Contains(help.stdout, "Domain skills (concepts, command choice, conventions):") {
		t.Fatalf("configured domain skills did not render as a list:\n%s", help.stdout)
	}
	docAt := strings.Index(help.stdout, "lark-cli skills read lark-doc")
	aAt := strings.Index(help.stdout, "lark-cli skills read lark-a")
	if docAt < 0 || aAt < 0 || docAt >= aAt {
		t.Fatalf("domain skill pointers missing or out of order (doc=%d a=%d):\n%s", docAt, aAt, help.stdout)
	}
	if strings.Contains(help.stdout, "lark-missing") {
		t.Fatalf("unreadable domain skill pointer was not filtered:\n%s", help.stdout)
	}
	for _, skill := range []string{"lark-doc", "lark-a"} {
		read := run(t, bin, "skills", "read", skill)
		if read.exit != 0 || !strings.Contains(read.stdout, "name: "+skill) {
			t.Errorf("rendered domain skill %q is not readable: exit=%d stdout=%s stderr=%s",
				skill, read.exit, read.stdout, read.stderr)
		}
	}

	commandHelp := run(t, bin, "docs", "+create", "--help")
	if commandHelp.exit != 0 {
		t.Fatalf("docs +create help: exit=%d stdout=%s stderr=%s",
			commandHelp.exit, commandHelp.stdout, commandHelp.stderr)
	}
	if strings.Contains(commandHelp.stdout, "lark-cli skills read lark-a") {
		t.Fatalf("domain-only skill leaked into command help:\n%s", commandHelp.stdout)
	}
}

